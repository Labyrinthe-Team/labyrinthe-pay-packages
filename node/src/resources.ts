/** @internal */
abstract class Resource {
  constructor(
    protected readonly transport: Transport,
    protected readonly autoReference: boolean,
  ) {}

  protected async reference(value: string | undefined): Promise<string | undefined> {
    return input.reference(value) ?? (this.autoReference ? `${AUTO_REFERENCE_PREFIX}${await randomUuid()}` : undefined);
  }

  protected async initiate(path: string, params: MobileMoneyParams, options: RequestOptions): Promise<Payment> {
    const body = input.compact({
      amount: input.amount(params.amount),
      currency: input.currency(params.currency),
      phone: input.phone(params.phone),
      country: input.country(params.country),
      provider: input.provider(params.provider),
      callback_url: input.callbackUrl(params.callbackUrl),
      customer_message: input.customerMessage(params.customerMessage),
      metadata: input.metadata(params.metadata),
    });
    const reference = await this.reference(params.reference);
    if (reference !== undefined) body['reference'] = reference;
    const response = await this.transport.request({
      method: 'POST',
      path,
      body,
      // Avec une référence, un renvoi rend le paiement existant : la relance est sûre.
      mode: reference === undefined ? 'throttled-only' : 'safe',
      paymentOnRefusal: true,
      signal: options.signal,
    });
    return toPayment(asObject(response.body, 'body')['data']);
  }
}

/** Collect from a customer (`client.deposits`, `POST /V2/deposits`). */
export class Deposits extends Resource {
  /**
   * Asks the customer to pay: they get a PIN prompt on their phone. The
   * returned payment is usually `pending`; its final status arrives by
   * notification on `callbackUrl` (or read it with `payments.get()`).
   * Only deliver an order on `completed`.
   *
   * A payment refused at initiation is returned with the `failed` status
   * (and `failure`), not thrown. A `ConnectionError` does not mean the
   * payment failed: resend with the same `reference`.
   */
  create(params: MobileMoneyParams, options: RequestOptions = {}): Promise<Payment> {
    return this.initiate('/deposits', params, options);
  }
}

/** Send money to a Mobile Money wallet (`client.payouts`, `POST /V2/payouts`). */
export class Payouts extends Resource {
  /**
   * Sends `amount` to the number. Your balance is debited immediately with
   * amount + payout fees, and credited back in full if the payout fails.
   */
  create(params: MobileMoneyParams, options: RequestOptions = {}): Promise<Payment> {
    return this.initiate('/payouts', params, options);
  }

  /**
   * Cancels a payout still queued by the provider (`gatewayStatus: ENQUEUED`,
   * see `isQueued()`). Asynchronous: the payout then moves to `failed` and
   * your balance is credited back. Not retried after a network error or a 5xx.
   */
  async cancel(id: string, options: RequestOptions = {}): Promise<Payment> {
    const response = await this.transport.request({ method: 'POST', path: `/payouts/${input.id(id)}/cancel`, mode: 'throttled-only', signal: options.signal });
    return toPayment(asObject(response.body, 'body')['data']);
  }
}

