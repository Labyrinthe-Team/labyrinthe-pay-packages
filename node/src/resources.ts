/** Prefix of the references generated by the SDK for payments sent without one. */
export const AUTO_REFERENCE_PREFIX = 'sdk_';

export interface RequestOptions {
  /** Abort the request (and its retries). */
  signal?: AbortSignal;
}

/** Fields shared by deposits and payouts. */
export interface MobileMoneyParams {
  /** Net amount, > 0, at most 2 decimals ("1500", "12.50"). Prefer strings. */
  amount: string | number;
  /** "CDF" or "USD". */
  currency: string;
  /** Local ("0812345678") or international ("+243812345678"), at most 20 characters. */
  phone: string;
  /** ISO alpha-3 country of the number (default: DR Congo for a local number). */
  country?: string;
  /** Provider code (inferred from the number when absent), e.g. VODACOM_MPESA_COD. */
  provider?: string;
  /**
   * Your reference, unique per token: 1 to 100 of A-Z a-z 0-9 . _ : -
   * Generated ("sdk_<uuid>") when absent and `autoReference` is on.
   */
  reference?: string;
  /** Public HTTPS URL receiving the final status notification. */
  callbackUrl?: string;
  /** Text shown to the customer: 4 to 22 letters, digits, spaces. */
  customerMessage?: string;
  /** Up to 20 key/value pairs (strings ≤ 255), returned as is. */
  metadata?: Record<string, string | number | boolean | null>;
}

