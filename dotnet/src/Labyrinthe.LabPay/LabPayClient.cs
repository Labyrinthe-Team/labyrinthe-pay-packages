using System;
using System.Net.Http;
using Labyrinthe.LabPay.Internal;
using Labyrinthe.LabPay.Resources;

namespace Labyrinthe.LabPay;

/// <summary>LabPay API V2 client. Thread-safe: create one and reuse it.</summary>
/// <example>
/// <code>
/// using var labpay = new LabPayClient(new LabPayClientOptions { ApiKey = "test_…" });
/// var payment = await labpay.Deposits.CreateAsync(new MobileMoneyRequest
/// {
///     Amount = 1000m, Currency = "CDF", Phone = "0813456789", Reference = "ORDER-42",
/// });
/// </code>
/// </example>
/// <remarks>A key starting with <c>test_</c> uses the sandbox: no real money moves, test balances and payments are
/// separate. Going live only means switching keys.</remarks>
public sealed class LabPayClient : IDisposable
{
    /// <summary>Version of this SDK (also in the <c>User-Agent</c> header).</summary>
    public const string Version = "0.1.0";

    /// <summary>Version of the LabPay API covered by this SDK (path prefix <c>/V2</c>).</summary>
    public const string ApiVersion = "V2";

    /// <summary>Prefix of the test keys.</summary>
    public const string TestKeyPrefix = "test_";

    /// <summary>Prefix of the references generated by the SDK for payments sent without one.</summary>
    public const string AutoReferencePrefix = "sdk_";

    private readonly string apiKey;
    private readonly HttpClient httpClient;
    private readonly bool ownsHttpClient;
    private bool disposed;

    /// <summary>Creates a client.</summary>
    /// <param name="options">Options; <see langword="null"/> reads <c>LABPAY_API_KEY</c> and <c>LABPAY_BASE_URL</c>.</param>
    /// <param name="httpClient">Your own <see cref="HttpClient"/> (proxy, <c>IHttpClientFactory</c>…); never disposed by
    /// the SDK. Configure its handler not to follow redirects. Without one, the SDK creates and owns its own.</param>
    /// <exception cref="InvalidArgumentException">Missing API key or invalid option.</exception>
    public LabPayClient(LabPayClientOptions? options = null, HttpClient? httpClient = null)
    {
        options ??= new LabPayClientOptions();
        var key = (options.ApiKey ?? Environment.GetEnvironmentVariable("LABPAY_API_KEY") ?? string.Empty).Trim();
        if (key.Length == 0)
        {
            throw new InvalidArgumentException(
                "A LabPay API token or test key (test_…) is required: set LabPayClientOptions.ApiKey or LABPAY_API_KEY.");
        }

        Transport.ValidateOptions(options.Timeout, options.MaxRetries, options.MaxRetryWait);
        var envBaseUrl = Environment.GetEnvironmentVariable("LABPAY_BASE_URL");
        string baseUrl;
        if (options.BaseUrl is { } configured && configured.Trim().Length > 0)
        {
            baseUrl = configured;
        }
        else if (envBaseUrl is { } fromEnv && fromEnv.Trim().Length > 0)
        {
            baseUrl = fromEnv;
        }
        else
        {
            baseUrl = LabPayClientOptions.DefaultBaseUrl;
        }

        apiKey = key;
        BaseUrl = Transport.NormalizeBaseUrl(baseUrl);
        ownsHttpClient = httpClient is null;
        this.httpClient = httpClient ?? CreateHttpClient();

        Transport = new Transport(key, BaseUrl, options.Timeout, options.MaxRetries, options.MaxRetryWait, this.httpClient, options.Logger, options.UserAgentSuffix);
        var auto = options.AutoReference;
        Deposits = new DepositsResource(Transport, auto);
        Payouts = new PayoutsResource(Transport, auto);
